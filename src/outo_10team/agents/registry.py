def create_teams(custom_names: dict[str, str] | None = None) -> list[TeamConfig]:
    names = custom_names or {}
    teams: list[TeamConfig] = []
    for default_name, description, agents in DEFAULT_TEAM_CONFIGS:
        team_name = names.get(default_name, default_name)
        teams.append(TeamConfig(team_name=team_name, default_name=default_name, description=description, agents=agents))
    return teams


def get_default_team_names() -> list[str]:
    return [name for name, _, _ in DEFAULT_TEAM_CONFIGS]


TEAMS: list[TeamConfig] = create_teams()


def get_team(name: str, teams: list[TeamConfig] | None = None) -> TeamConfig:
    team_list = teams or TEAMS
    for team in team_list:
        if team.team_name == name or team.default_name == name:
            return team
    raise ValueError(f"Team not found: {name}")


def get_all_team_names(teams: list[TeamConfig] | None = None) -> list[str]:
    return [t.team_name for t in (teams or TEAMS)]


def get_team_by_default_name(default_name: str, teams: list[TeamConfig] | None = None) -> TeamConfig | None:
    for team in (teams or TEAMS):
        if team.default_name == default_name:
            return team
    return None
